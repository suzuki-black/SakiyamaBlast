out = []
def print(*a, **k):          # noqa: A001 - 出力を溜めてから流す
    out.append(' '.join(str(v) for v in a))

print("/* 自動生成: tools/mkkanji.py。16x16 の 1bpp。 */")
print("const uint8_t kanji_bits[%d][32] = {" % len(order))
for k in order:
    b = []
    for r in G[k]:
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= 1 << (15 - i)
        b += [v >> 8, v & 0xFF]
    print("    { /* %s */" % k)
    for i in range(0, 32, 8):
        print("      " + ", ".join("0x%02X" % x for x in b[i:i+8]) + ",")
    print("    },")
print("};")

import sys

if '--bin' in sys.argv:
    # **絵と同じ扱いにする。** 字の形は ROM の専用セグメントへ置き、読むときだけ
    # 窓を向ける (src/kanji.c)。窓 (0xA000-0xBFFF) は満杯なので、
    # 576バイトの表をそこから追い出すのが目的 (2026-10-23)。
    i = sys.argv.index('--bin')
    blob = bytearray()
    for k in order:
        for r in G[k]:
            v = 0
            for j, c in enumerate(r):
                if c == '#':
                    v |= 1 << (15 - j)
            blob += bytes((v >> 8, v & 0xFF))
    open(sys.argv[i + 1], 'wb').write(bytes(blob))
    with open(sys.argv[i + 2], 'w') as f:
        f.write('/* 自動生成: tools/mkkanji.py --bin。手で編集しない。 */\n')
        f.write('#define KANJI_N %d\n' % len(order))
    sys.stderr.write('%s: %d バイト (%d 字)\n' % (sys.argv[i + 1], len(blob), len(order)))
    sys.exit(0)
body = '\n'.join(out) + '\n'

if '--preview' in sys.argv:      # 字を拡大画像に起こして目で見る
    from PIL import Image
    Z, PAD = 12, 8
    cols = 8
    rows_n = (len(order) + cols - 1) // cols
    cw = 16 * Z + PAD * 2
    im = Image.new('L', (cw * cols, cw * rows_n), 235)
    for i, k in enumerate(order):
        ox = (i % cols) * cw + PAD
        oy = (i // cols) * cw + PAD
        for r in range(16):
            for c in range(16):
                v = 40 if G[k][r][c] == '#' else 252
                for y in range(Z):
                    for x in range(Z):
                        im.putpixel((ox + c * Z + x, oy + r * Z + y), v)
    p = sys.argv[sys.argv.index('--preview') + 1]
    im.save(p)
    sys.stderr.write('-> %s\n' % p)
    sys.exit(0)
if '--write' in sys.argv:    # src/kanji.c の表を差し替える
    p = __file__.rsplit('/tools/', 1)[0] + '/src/kanji.c'
    cur = open(p).read()
    a = cur.index('/* 自動生成: tools/mkkanji.py')
    b = cur.index('};\n', a) + 3
    open(p, 'w').write(cur[:a] + body + cur[b:])
    sys.stderr.write('-> src/kanji.c を差し替えた (%d 字)\n' % len(order))
else:
    sys.stdout.write(body)
