def build(items, path, check_one_colour_per_row):
    # **既にある絵より少ないセル数で上書きしない。** この表は「たたき台」なので
    # 古くなりがちで、うっかり実行すると PNG のほうにある絵を消してしまう
    # (実際に sprites.png を 26 セルから 5 セルへ潰した)。
    if os.path.exists(path):
        have = Image.open(path).size[0] // 16
        if have > len(items):
            # **中断ではなく、その PNG だけ飛ばす。** 中断すると、片方の表が古いだけで
            # もう片方も作り直せなくなる。
            print("!! %s には %d セルあるのに、この表は %d セルしかありません。"
                  "表が古いので上書きしません（この1枚だけ飛ばします）。"
                  % (path, have, len(items)))
            return
    im = Image.new("RGBA", (16 * len(items), 16), (0, 0, 0, 0))
    px = im.load()
    for i, (name, rows) in enumerate(items):
        for y, row in enumerate(rows):
            if check_one_colour_per_row:
                used = {c for c in row if c != '.'}
                if len(used) > 1:
                    raise SystemExit("%s の %d 行目に色が %d 種あります。"
                                     "mode-2 スプライトは1行1色です: %s"
                                     % (name, y, len(used), row))
            for x, ch in enumerate(row):
                idx = LEGEND[ch]
                if idx == 0:
                    continue
                r, g, b = rgb255(idx)
                px[i * 16 + x, y] = (r, g, b, 255)
    im.save(path)
    print("%s: %d セル (%s)" % (path, len(items), ", ".join(n for n, _ in items)))


build(SPRITES, "assets/sprites.png", True)
build(TILES, "assets/tiles.png", False)
