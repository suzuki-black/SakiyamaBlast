/*
 * SakiyamaBlast - 槍 (赤い敵のひと突き)
 *
 * **敵の動詞が「歩く」しか無く、脅威も「触れたら即死」しか無かった**ので、
 * 赤にだけ間合い1升の攻撃を持たせた (2026-10-29、作者の案)。
 *
 * **赤だけなのは、色がアルゴリズムの印だから。** 赤は自機の升をそのまま狙う
 * 追いかけ役なので「間合いに入ったら必ず仕掛ける」という読みやすい約束にできる。
 * 他の3種は待ち伏せ・気まぐれ・お惚けで、間合いの概念が無いほうが性格が立つ。
 * **第二坑 (面4) から**。入口の3面は従来どおりにして、学ぶ場を残す。
 *
 * 手順 (`en_spear` の1バイトを SPEAR_TOTAL から減らしていく):
 *
 *   SPEAR_TOTAL .. REST+HOLD+1   構え。**その場で固まる**
 *   REST+HOLD                    突く。穂先の升に自機が重なっていればミス
 *   REST+HOLD-1 .. REST+1        突き出したまま (絵を前へずらす)
 *   REST .. 1                    動けるが、次の突きはまだ出せない
 *
 * **構えている間は動かない。** ここが読みの時間で、同時に**つるはし (間合い2升)
 * の的**にもなる。よろけさせれば突きは中断する。「仕掛けてきた赤を、間合いの
 * 外から叩いて止める」が成立するようにしてある。
 *
 * **土越しには刺さらない。** 隣の升でも掘り跡の膜 (`cell_linked`) で隔てられて
 * いれば突けない。敵が歩いて行けない升へ槍だけ届くのは筋が通らない。
 *
 * **面の頭で捨てる処理は要らない。** 湧いた敵は必ず `en_warm` の点滅を通り、
 * その間 `spear_tick` が `en_spear` を 0 にするので、勝手に揃う
 * (そのために `enemy_update` では**点滅の判定より前**で呼んでもらっている)。
 *
 * 止めるのは `en_pause` を毎フレーム立て直す形にしてある。移動を止める枝は
 * `enemy_update` に既にあるので、**RAM 実行側に新しいコードをほとんど足さずに済む**
 * (RAM 実行の空きは数十バイトしかない)。
 *
 * **このファイルは固定領域のサイズに直結する。** 書き足すときは `make` の最後に
 * 出る「free ... bytes」を必ず見ること。最初に書いたときは 616 バイトあって
 * 固定領域 (当時の空き 410) を溢れさせた。16bit の演算と switch をやめ、
 * 升で見るように書き直して縮めてある。
 */
#include "game.h"

uint8_t en_spear[ENEMY_MAX];     /* 突きの進行。0 = 何もしていない */

/* DIR_NONE/UP/DOWN/LEFT/RIGHT をそのまま添字にする。switch より小さい。 */
static const int8_t sp_dc[5] = { 0,  0,  0, -1,  1 };
static const int8_t sp_dr[5] = { 0, -1,  1,  0,  0 };

/* **向いている先の升に自機が重なっているか。** 体ではなく1升先を見るので、
   「触れたら死ぬ輪」が向いている側にだけ1升ぶん伸びた、と読める。
   重なりの幅は接触死と同じ 12px。

   **符号なしで畳んである** (固定領域が数十バイト単位で足りないため)。
   升が盤外へ出ると `tc` は 255 側へ回り込むので、`>= COLS` の1回で両端を見られる。
   `|d| < 12` も `(d + 11) < 23` の1回で済む。 */
static uint8_t player_ahead(uint8_t i)
{
    uint8_t d = en_dir[i];
    uint8_t tc = (uint8_t)((en_x[i] >> 4) + sp_dc[d]);
    uint8_t tr = (uint8_t)((en_y[i] >> 4) + sp_dr[d]);

    if (tc >= COLS || tr >= ROWS) {
        return 0;
    }
    return (uint8_t)((uint8_t)(px - (uint8_t)(tc << 4) + 11) < 23
                     && (uint8_t)(py - (uint8_t)(tr << 4) + 11) < 23);
}

void spear_tick(uint8_t i)
{
    /* よろけ・透明化・湧き待ちでは構えを捨てる。叩けば止まる、が counterplay。 */
    if (en_stun[i] || en_ghost[i] || en_warm[i]) {
        en_spear[i] = 0;
        return;
    }
    if (en_spear[i]) {
        en_spear[i]--;
        /* **当たるのは穂先を出し切った最後の1フレーム。**
           出した最初のフレームで当てていたときは、**突きの絵が1フレームも
           描かれないまま死んだ** (死ぬと画面が止まるため。openMSX で確認)。
           先に穂先を見せてから当てることで、「出た」→「刺さった」の順になる。
           そのぶん踏み込んだ側にも SPEAR_HOLD ぶんの逃げる猶予が生まれる。 */
        if (en_spear[i] == (uint8_t)(SPEAR_REST + 1)
            && !invuln && !dead && player_ahead(i)) {
            dead = 1;
        }
        if (en_spear[i] > SPEAR_REST) {
            en_pause[i] = 1;         /* 構え〜突きの間は動かない */
        }
        return;
    }
    /* 赤だけ、第二坑 (面4) から。裏面は最初から持つ。 */
    if (en_kind[i] != EN_RED || !(loop_n || stage >= SPEAR_STAGE)) {
        return;
    }
    if ((en_x[i] & 15) || (en_y[i] & 15)) {
        return;                      /* 節点でだけ構える (間合いが升で決まる) */
    }
    /* **膜を先に見る。** こちらが升の範囲も確かめてくれるので、`player_ahead`
       は盤外を気にしなくてよくなる (構えてから突くまで敵は固まっているので、
       突く瞬間にも同じ位置関係のまま)。 */
    if (!cell_linked((int8_t)(en_x[i] >> 4), (int8_t)(en_y[i] >> 4), en_dir[i])) {
        return;                      /* 土の膜越しには刺さらない */
    }
    if (!player_ahead(i)) {
        return;
    }
    en_spear[i] = SPEAR_TOTAL;
    en_pause[i] = 1;
}

/* 突き出している最中か。絵をその向きへずらして「突いた」を見せる。 */
uint8_t spear_jab(uint8_t i)
{
    /* REST+1 .. REST+HOLD。引き算の回り込みで1回の比較に畳んである。 */
    return (uint8_t)((uint8_t)(en_spear[i] - SPEAR_REST - 1) < SPEAR_HOLD);
}
