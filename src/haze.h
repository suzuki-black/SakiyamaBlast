/*
 * SakiyamaBlast - 陽炎 (かげろう)
 *
 * 体温が危険域に入ったとき、盤面をラスタごとに横へ ±1〜2px ずらす。
 * 真夏のアスファルトの陽炎のような、ごく小さい振り幅の揺らぎ。
 *
 * **VRAM を一切触らない。** V9938 のライン割り込み (R#19 + R#0 の IE1) で
 * 表示位置調整レジスタ (R#18) を1画面に何度か書き替えるだけ。
 * 描画コスト (このゲームの本当のボトルネック) はゼロ。
 */
#ifndef HAZE_H
#define HAZE_H

#include "msx.h"

/*
 * 分割数。多いほど帯の継ぎ目が細かくなって陽炎らしくなるが、
 * **1バンドにつき1フレーム1回の割り込みが増える。**
 *
 * 重いのは自前の処理ではなく **MSX BIOS が割り込み源を判定するまでの往復**で、
 * その BIOS は内蔵 ROM にある。だから **turbo R の R800 DRAM モードでは
 * ほぼタダになる**（実機実測: 12回で 57→56）。Z80 機では 1本につき約1.4 fps
 * 落ちる（12回で 55→44）ので、**機種で分ける。**
 *
 * **位相の進みとの積が 32 になるように選ぶ。** そうすると盤面全体でちょうど
 * 2周になり、分割数を変えても**波の形は変わらず、標本が細かくなるだけ**になる。
 */
#define HAZE_BANDS_Z80 11      /* 11 x 3 = 33 ≒ 32。16ライン刻み */
#define HAZE_BANDS_TR  16      /* 16 x 2 = 32。11ライン刻み。turbo R のみ */
#define HAZE_BANDS     HAZE_BANDS_TR   /* 表の大きさは多いほうに合わせる */

void haze_init(void);            /* H.KEYI へフックを入れる。起動時に1回 */
/* 揺らぎの振幅 (px)。**±2px・11分割が作者の選んだ形**
   (±1px や 5分割も試作して見比べた。振幅より分割数のほうが見え方に効く)。 */
#define HAZE_AMP 2
/* 毎フレーム呼ぶ。on=0 で切。
   **代償: 掘っているときの fps が 55 -> 44 に落ちる** (openMSX 実測)。
   分割1本につき約1.4 fps。重いのはこちらの処理ではなく、MSX BIOS が
   割り込み源を判定するまでの往復 (1回あたり約1000サイクル)。
   だから**体温が危険域のときだけ**出す。 */
void haze_tick(uint8_t on);

/* --- 割り込みハンドラ (lowlevel.s) が読む表。C 側が毎フレーム作る --- */
extern uint8_t haze_row[HAZE_BANDS + 1];   /* 各バンドの R#19 の値 */
extern uint8_t haze_adj[HAZE_BANDS + 1];   /* 各バンドで R#18 に書く値 */
extern uint8_t haze_n;                     /* 分割数 (0 = ハンドラは何もしない) */
extern uint8_t haze_i;                     /* 次に処理するバンド */
extern uint16_t haze_hits;                 /* ハンドラが走った回数 (計測用) */
void haze_hook(void);                      /* H.KEYI へ jp を書き込む */

#endif
