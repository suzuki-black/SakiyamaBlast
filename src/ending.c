/*
 * SakiyamaBlast - エンドロール (ゆっくり流れるクレジット)
 *
 * **画面ごと縦にずらす** (V9938 の R#23 = 垂直オフセット)。1フレームに1画素も
 * 動かさずに済むので、流す速さを変えても処理は増えない。**書き写しはしない。**
 *
 * **ページ1 (VRAM 0x8000-) に描く。** ページ0 の下のほう (0x7400-0x7FFF) には
 * スプライトの表が載っていて、R#23 は 256行を輪にして回すので、そのまま使うと
 * 表の上に文字を書いてしまう。ページ1 なら 256行まるごと空いている。
 * コマンドも文字描画も「y に 256 を足す」だけでページ1 を指す
 * (SCREEN 5 では VRAM 全体が 256x1024 の絵として見えているため)。
 *
 * 流れ方:
 *   見えているのは [px, px+211]。**その下の [px+224, px+239] に次の1行を置く。**
 *   16画素進むごとに1行ぶん用意するので、文字は画面の下から入ってくる。
 *   帯の位置は 16の倍数に揃えてあり、256 をまたがないので消しも1回で済む。
 *
 * 文面は `src/endtext.c` (曲と同じセグメント14)。窓を向けると**この関数自身が
 * 消える**ので、`blob_read()` で1行ぶんを RAM へ写してから描く。
 */
#include "game.h"
#include "vdp.h"
#include "msx.h"
#include "text.h"
#include "endtext.h"
#include "end_omote_pal.h"
#include "end_ura_pal.h"

#define PAGE1     256           /* y に足すとページ1 */
#define ROW_H      16           /* 1行の高さ (16の倍数。256 を割り切ること) */
#define LEAD      224           /* 画面の下から何画素先に用意するか */
#define ROLL_WAIT   4           /* 何フレームで1画素流すか (大きいほどゆっくり) */
/* **終わりの塊** (献辞5行 + 空き + 昔話の結び3行 + 空き + 礼 + 空き + 案内 = 13行) を、
   止まったあと画面に残す。**流れている途中と同じ位置でちょうど止まる**ので、
   止めるときに消すことも描き直すこともしない (`ending_tick()` を見ること)。
   **13行が上限。** 1行16画素 × 13 = 208画素で、画面の212行にちょうど収まる
   (上下に2画素ずつ)。**これ以上は足せない** —— 足すなら献辞か結びのどれかを削る。 */
#define ROLL_TAIL  13
#define ROLL_TOP    2           /* 塊の上端 (13行 = 208画素を 212行の中央へ) */

/*
 * **一枚絵もページ1 に置いて、ロールと一続きに流す** (作者の希望、2026-11-16)。
 * 絵は 0..211行、クレジットはその下 (224行目から) に用意するので、**R#23 を
 * 進めるだけで絵が上へ抜けていき、そのあとをクレジットが追ってくる。**
 * 絵を別に消す必要はない —— 16画素ごとの帯の消しが、画面から抜けた行をそのまま
 * 消していく (消すのは常に画面の 12行下なので、見えている絵は削られない)。
 *
 * **絵が抜け切るまで文字を出さない。** 一枚絵は自前のパレット16色で塗ってあり、
 * ゲームのパレットとは別物なので、**絵と文字を同時に出すとどちらかの色が壊れる**
 * (裏の絵には黒が1色も無く、`COL_TUNNEL` が明るい緑灰になる)。だから絵が画面から
 * 抜けた 212画素目でパレットを戻し、クレジットはその後ろから入ってくる。
 *
 * **抜けるまでは4倍速で流す** (1画素/フレーム)。ロールの速さのままだと14秒かかる。
 *
 * **1行目を用意するのは絵が抜ける前でよい。** 用意する場所は画面の 224行下
 * なので、**描いている間はまだ見えていない**。色が問題になるのは「見えたとき」
 * だけなので、`ROLL_FROM` 画素目から用意を始めれば、絵が抜けた 9画素後には
 * もう1行目が下から入ってくる。
 */
#define PIC_H     212           /* 一枚絵の高さ = 画面の高さ。ここで色を戻す */
#define SLIDE_WAIT  1           /* 絵を流している間の1画素あたりのフレーム数 */
/* 最初の行を用意する位置。**`ROW_H` の倍数**で、**`+ LEAD - 211 >= PIC_H`**
   (= 見え始めるのが絵の抜けたあと) を満たすこと。208 + 13 = 221 >= 212。 */
#define ROLL_FROM 208

/* **1行ぶんの受け皿はスタックに取る。** 変数 (0xC000-0xC97F) に 33バイトの配列を
   置いたら RAM 実行の領域へ食い込んだ (`tools/ihx2rom.py` が止めてくれた)。
   スタックは 0xF380 から下へ伸びて実測で 0xF30F までしか使っていないので余裕がある。 */
static uint16_t roll_px;           /* 流した画素数 */
static uint8_t  roll_i;            /* 次に用意する行 */
static uint8_t  roll_t;            /* 1画素ぶんの待ち */

#define ROLL_OVER 0xFFFF        /* 置き直しまで済んだ印 (変数を増やさないため) */

/*
 * どこまで流したら止まるか。**行数ではなく「用意した帯の数」で決める。**
 *
 * **どちらの物語も、全102行のうち一部しか流さない。**
 *   表 ... 0..24 と 45..101 = 82本 (裏の物語20行を飛ばす)
 *   裏 ... 25..101        = 77本 (表の物語25行を飛ばす)
 * 行数 (99) で止める位置を決めていたときは、表で 320画素、裏で 400画素ぶん
 * 流しすぎていた。`PUSH SPACE KEY` を含む終わりの塊が画面の上へ抜けてしまい、
 * 真っ暗なまま9秒 (裏は14秒) 流れてから置き直していた
 * (作者の報告、2026-11-06「最後の英文すら流れていってしまった」。
 *  openMSX で両方を実測: 表 1622->1302、裏 1622->1222 画素)。
 *
 * **一枚絵を流すぶん (`ROLL_FROM`) を足す。** 1行目を用意するのが 0画素目から
 * `ROLL_FROM` 画素目へずれただけなので、止める位置も同じだけ後ろへずらせば、
 * 終わりの塊が止まる場所は前と1画素も変わらない (`ROLL_FROM` は `ROW_H` の倍数)。
 */
static uint16_t roll_end(void)
{
    uint8_t n = (uint8_t)(END_ROLL_N
                          - (loop_n ? ROLL_URA : (ROLL_CREDITS - ROLL_URA))
                          - ROLL_TAIL);
    return (uint16_t)n * ROW_H + LEAD - ROLL_TOP + ROLL_FROM;
}

/* 一枚絵がまだ画面に残っているか (残っている間はスペースで飛ばさせない)。 */
uint8_t ending_sliding(void)
{
    return (uint8_t)(roll_px < PIC_H);
}

/*
 * ページ1 の行番号から y を作る (256 を足すだけ)。
 *
 * **わざわざ関数にしてある。** 呼び出し元で `(uint16_t)(PAGE1 + band)` と書くと、
 * SDCC が **D レジスタに 0 が入っているという誤った前提**で `inc d` だけを吐き、
 * 直前の比較で D に残っていた値がそのまま上位バイトになる。書き込み先が
 * 0x8808 ではなく 0x0808 になって、**エンドロールが1文字も描かれなかった**
 * (2026-10-25。openMSX の `debug set_bp` で `vdp_setwrite` の引数を見て判明)。
 * 関数の頭ではレジスタの思い込みが無いので、素直に16ビットの値が組み立てられる。
 *
 * **ページ1 の y は必ずこれを通す。** 定数どうしの足し算 (`PAGE1` 単体) は畳まれるので
 * 安全だが、**8ビットの値と足すところは一つ残らずここへ**。規則を一つにしておけば、
 * 後から足した1行で踏み直すことがない。
 * **ここを触ったら `build/ending.asm` を目で確かめること。**
 */
static uint16_t page1_y(uint8_t line)
{
    return (uint16_t)(PAGE1 + (uint16_t)line);
}

/* 窓を曲のセグメントへ向けて1行ぶん写す。**窓はこの中で元へ戻る。** */
static void fetch(uint8_t i, uint8_t *dst)
{
    blob_seg = MUSIC_SEG;
    blob_off = (uint16_t)((uint16_t)end_roll - 0x2000 + 0xA000
                          + (uint16_t)i * EROW_SIZE);
    blob_dst = dst;
    blob_len = EROW_SIZE;
    blob_read();
}

/* 1行を帯の中へ描く。中央寄せ。 */
static void draw_row(uint8_t i, uint16_t y)
{
    uint8_t rbuf[EROW_SIZE];
    uint8_t n = 0;
    uint8_t sc, col;
    uint16_t x;
    fetch(i, rbuf);
    if (!rbuf[1]) {
        return;                              /* 空行 */
    }
    sc = (uint8_t)((rbuf[0] == EROW_ATTR_T) ? 2 : 1);
    col = (uint8_t)((rbuf[0] == EROW_ATTR_N) ? COL_WHITE : COL_FUSE);
    while (rbuf[1 + n]) {
        n++;
    }
    /* **x は偶数にする** (1バイトが2画素なので、奇数だと隣の画素を巻き込む)。 */
    x = (uint16_t)(((256 - (uint16_t)n * (uint16_t)(8 * sc)) >> 1) & 0xFFFE);
    text_draw(x, y, (const char *)(rbuf + 1), col, COL_TUNNEL, sc);
}

/*
 * **1行を8回に分けて描く。** 1行 (28文字) をまとめて描くと主ループが **0.12秒**
 * 止まり、`snd_tick()` が回らないぶん**音が間延びする** (作者の報告、2026-11-16。
 * openMSX で実測)。走査行を1本ずつにすれば1回が8分の1で済む。
 *
 * **どこまで描いたかを覚える変数は持たない。** 変数の領域は RAM 実行の領域と
 * 接していて1バイトも空きがない (`tools/ihx2rom.py` が止める)。流す位置
 * `roll_px` の下位4ビットがそのまま進み具合になっているので、そこから引く。
 */
static void draw_part(uint8_t i, uint16_t y, uint8_t part)
{
    text_row0 = part;
    text_rows = 1;
    draw_row(i, y);
    /* **必ず戻す。** 空行のときは draw_row が text_draw を呼ばずに帰るので、
       ここで戻さないと次に誰かが描く文字が1本線になる。 */
    text_row0 = 0;
    text_rows = 8;
}

/*
 * **ロールの前に一枚絵を出す。** 表は炭鉱長屋の茶の間、裏はドームの温水プール
 * (`docs/ENDING_ART_BRIEF.md`)。やり方は `title_draw()` とほぼ同じで、
 * ROM の4セグメントを VRAM の 8KB ブロック 0..3 へそのまま流し込む。
 *
 * **ただし置き先はページ1 (0x8000-) で、タイトルとはそこだけ違う。**
 * ロールと同じページに置くからこそ、R#23 を進めるだけで絵が上へ抜けていき、
 * そのあとをクレジットが追ってくる (`PIC_H` と `ROLL_FROM` の説明を見ること)。
 * **絵の 0..211行に対し、クレジットは 224行目から**用意するので重ならない。
 *
 * **ここは窓2 (PLAYCODE) に置いてよい。** 切り替えるのは1枚目の窓 (0xA000) で、
 * 0x8000 の窓はそのまま PLAYCODE を向いている。だから `title_draw()` と違って
 * 固定領域に置く必要がない (固定領域の空きはもう 2.7KB しかない)。
 *
 * **絵のパレットに塗り替わる。** 戻すのは `ending_tick()` で、絵が画面から
 * 抜け切った瞬間 (`PIC_H` 画素目)。
 */
void ending_pic(void)
{
    uint8_t i, blk;
    uint16_t left = 27136;          /* 256 * 212 / 2 */
    const uint8_t *pal = loop_n ? end_ura_palette : end_omote_palette;
    uint8_t seg = (uint8_t)(loop_n ? END_URA_SEG : END_OMOTE_SEG);

    for (i = 0; i < 16; i++) {
        VDP_REG(16, i);
        vdp_wpal(pal[i * 2]);
        vdp_wpal(pal[i * 2 + 1]);
    }
    VDP_REG(7, 0);                  /* 背景色は黒。パレット0番は背景色として出る。 */

    for (blk = 0; blk < 4 && left; blk++) {
        vdp_blklen = (left > 8192) ? 8192 : left;
        bank_select((uint8_t)(seg + blk));
        /* ページ1 の頭 = 0x8000。ブロック3 でも 0xE000 なので16ビットに収まる。 */
        vdp_setwrite((uint16_t)(0x8000 + ((uint16_t)blk << 13)));
        vdp_wblock(BANK_WINDOW);
        left = (uint16_t)(left - vdp_blklen);
    }
    bank_select(DATA_SEG);      /* 窓を絵と曲へ戻す。戻し忘れると音も絵も壊れる */
}

/*
 * **ロールの用意。一枚絵を置く前に呼ぶこと** (ページ1 をまるごと消すため)。
 * 曲を鳴らし始める前にここまで済ませておく。
 *
 * **こうしないと曲が間延びする** (作者の報告、2026-11-16)。音は主ループ1周に
 * 1回しか進まない (`snd_catch_up`) ので、鳴っている最中に重い描画を挟むと、
 * そのぶん音が伸びる。実測で 0.25秒 止まっていた。
 *
 * **消す色は 0番。** 一枚絵が流れている間、その下に見えるのがこの色になる。
 * 0番は背景色レジスタ (R#7) が指す色でもあるので、**画面の縁と同じ色**に
 * なって落ち着く (`COL_TUNNEL` で消すと、裏の絵のパレットでは明るい緑灰になる)。
 * ゲームのパレットでは 0番も `COL_TUNNEL` も黒なので、戻したあとは差が出ない。
 */
void ending_start(void)
{
    roll_px = 0;
    roll_t = 0;
    vdp_fill(0, PAGE1, 256, 256, 0);            /* ページ1 を消す */
    /* **スプライトを止める。** R#23 でずらすと**スプライトも一緒にずれる**ので、
       場外 (Y=212) へ退避した絵がずらした量だけ画面内へ入ってくる
       (15面クリアから入ると自機も岩も残って見えた。作者の報告、2026-10-25)。
       エンドロールでスプライトは1枚も使わないので、面ごと止めるのが確実。 */
    VDP_REG(8, 0x0A);                           /* SPD=1 / 64K DRAM */
    VDP_REG(23, 0);
    /* **裏面をクリアしたときは裏の物語から流す。** 表は 0 から。
       共通部分 (題・クレジット・献辞) は両方とも同じ行を使う。
       **1行目もここでは描かない** —— 一枚絵が抜けてから流れ始める。 */
    roll_i = (uint8_t)(loop_n ? ROLL_URA : 0);
}

/* 表示をページ1 (ロール) へ切り替える。**レジスタ1本なので一瞬で終わる。**
   重い用意は `ending_start()` が先に済ませてある。 */
void ending_show(void)
{
    VDP_REG(2, 0x3F);
}

/* 表示をページ0 へ戻す。**エンドロールから抜けるときに必ず呼ぶ。** */
void ending_stop(void)
{
    VDP_REG(23, 0);
    VDP_REG(2, 0x1F);
    VDP_REG(8, 0x08);       /* スプライトを戻す (SPD=0 / 64K DRAM) */
}

void ending_tick(void)
{
    uint16_t band;
    uint8_t lo;
    if (roll_px == ROLL_OVER) {
        return;                         /* 流し終わった。画面はもう出来ている */
    }
    if (roll_px >= roll_end()) {
        /*
         * **止めるだけ。消しも描き直しもしない** (2026-11-16)。
         *
         * 以前はここで R#23 を 0 へ戻し、見えている 212行を消して、終わりの塊を
         * 置き直していた。**それが 0.3秒 主ループを止めて、曲がもたついていた**
         * (作者の報告。`snd_catch_up()` の取りこぼしの上限が4フレームなので、
         * 15フレームぶんの停止はそのまま曲の遅れになる)。
         *
         * **置き直す必要はもう無い。** `roll_end()` を「実際に流す帯の数」から
         * 出すように直した日 (2026-11-07) に、**終わりの塊はちょうど
         * `ROLL_TOP` の位置で止まる**ようになっている (いちばん下の行の上端が
         * 194画素目 = ROLL_TOP + 12行)。見えている行はどれも、画面へ入る12行前に
         * 帯の消しを通っているので、1周前の残りも無い。
         * **消して描き直していたのは、塊が上へ抜けてしまっていた頃の名残。**
         */
        roll_px = ROLL_OVER;
        return;
    }
    /* 一枚絵が抜けるまでは4倍速 (1画素/フレーム)。 */
    if (++roll_t < (uint8_t)((roll_px < PIC_H) ? SLIDE_WAIT : ROLL_WAIT)) {
        return;
    }
    roll_t = 0;
    roll_px++;
    VDP_REG(23, (uint8_t)roll_px);
    /* **絵が画面から抜けた瞬間にパレットを戻す。** ここより前に文字を出すと
       絵のパレットで塗られてしまう (だから下の帯も `ROLL_FROM` まで文字を置かない)。
       絵はもう1画素も見えていないので、切り替わるところは見えない。 */
    if (roll_px == PIC_H) {
        set_game_palette();
    }
    lo = (uint8_t)(roll_px & (ROW_H - 1));
    /* y の作り方は `page1_y()` の説明を見ること (SDCC の都合で関数にしてある)。 */
    if (lo == 0) {
        band = page1_y((uint8_t)(roll_px + LEAD));
        /* **消す色は流している間だけ 0番。** 理由は `ending_start()` の説明。
           消すのは画面の12行下なので、見えている一枚絵は削られない。 */
        vdp_fill(0, band, 256, ROW_H,
                 (uint8_t)((roll_px < PIC_H) ? 0 : COL_TUNNEL));
        if (roll_px < ROLL_FROM) {
            return;                     /* 絵を流している間は行を用意しない */
        }
        if (roll_i == ROLL_URA && !loop_n) {
            roll_i = ROLL_CREDITS;      /* 表は裏の物語を飛ばす */
        }
        /* **文字はまだ置かない。** 次の8段で1本ずつ置く。`roll_i` は帯を1つ
           用意するごとに必ず1つ進めて、**「この帯の行 = roll_i - 1」**にして
           おく (進み具合を覚える変数を増やさずに済む)。文面を使い切った
           あとは END_ROLL_N + 1 で止まり、下の `<=` が偽になって何も描かない。 */
        if (roll_i <= END_ROLL_N) {
            roll_i++;
        }
    } else if (lo <= 8 && roll_px > ROLL_FROM && roll_i <= END_ROLL_N) {
        /* 帯の y は 16画素の切りのよいところ。下位4ビットを落とせば、
           用意したときと同じ値になる (8ビットで足りる)。 */
        band = page1_y((uint8_t)((uint8_t)((uint8_t)roll_px & 0xF0) + LEAD));
        draw_part((uint8_t)(roll_i - 1), band, (uint8_t)(lo - 1));
    }
}
